"""Opt-in truthful consumer dialect marker and exact source preservation."""
from dataclasses import replace
from hashlib import sha256,md5
import unittest

from tests.unit.test_gui_native_trial_copy import recipe_fixture
from tools.gui_native_trial_copy import rebuild_native_trial_copy, STUDIO_NATIVE_METADATA_MARKER
from tools.gui_native_trial_trace import native_profile_caps,interpret_native_trial
from tools.prepare_two_tier_intents import freeze_supported_graph
from tests.unit.native_trial_fixture import change_member
from tools.package_gui_native_trial import NativePackagePolicy,build_native_trial_package
from io import BytesIO
from zipfile import ZipFile


def orca_recipe():
    old=recipe_fixture(annotations=True)
    header=b'; generated by OrcaSlicer synthetic contract fixture\n'
    source=header+old.source_bytes
    project=change_member(old.project_bytes,'Metadata/plate_1.gcode',source)
    project=change_member(project,'Metadata/plate_1.gcode.md5',md5(source).hexdigest().upper().encode())
    profile=native_profile_caps(source,project,old.geometry_project_bytes,old.limits)[0]
    context=replace(old.context,source_sha256=sha256(source).hexdigest(),project_sha256=sha256(project).hexdigest(),
        body_start_offset=old.context.body_start_offset+len(header),body_end_offset=old.context.body_end_offset+len(header),
        effective_profile_identity=profile.projection_identity)
    trace=interpret_native_trial(source,project,old.producer_bytes,context,
        geometry_project=old.geometry_project_bytes,limits=old.limits,cancelled=lambda:False)
    insertion=old.insertions[0]
    plan=freeze_supported_graph(tuple(replace(p.intent,source_context_identity=trace.context_identity) for p in insertion.plan.paths),
        source_context_identity=trace.context_identity,policy=insertion.policy,graph_policy=insertion.plan.graph_policy,cancelled=lambda:False)
    return replace(old,source_bytes=source,project_bytes=project,context=context,insertions=(replace(insertion,byte_offset=insertion.byte_offset+len(header),plan=plan),))


class StudioNativeMetadataTests(unittest.TestCase):
    def test_prefix_package_rebuild_and_md5_remain_closed(self):
        recipe=orca_recipe()
        recipe=replace(recipe,copy_policy=replace(recipe.copy_policy,enable_studio_native_metadata=True))
        copy=rebuild_native_trial_copy(recipe,cancelled=lambda:False)
        package=build_native_trial_package(recipe.project_bytes,recipe.source_bytes,copy,copy_recipe=recipe,
            policy=NativePackagePolicy(recipe.context.source_sha256,recipe.context.project_sha256))
        self.assertEqual(set(package.changed_members),{'Metadata/plate_1.gcode','Metadata/plate_1.gcode.md5'})
        with ZipFile(BytesIO(package.archive_bytes)) as archive:
            self.assertEqual(archive.read('Metadata/plate_1.gcode'),copy.output_bytes)
            self.assertEqual(archive.read('Metadata/plate_1.gcode.md5'),md5(copy.output_bytes).hexdigest().upper().encode())
        with self.assertRaisesRegex(ValueError,'stale-copy'):
            build_native_trial_package(recipe.project_bytes,recipe.source_bytes,replace(copy,adapter_prefix=b''),copy_recipe=recipe,
                policy=NativePackagePolicy(recipe.context.source_sha256,recipe.context.project_sha256))

    def test_default_disabled_and_enabled_marker_unique_in_tracked_prefix(self):
        recipe=orca_recipe()
        baseline=rebuild_native_trial_copy(recipe,cancelled=lambda:False)
        self.assertNotIn(STUDIO_NATIVE_METADATA_MARKER,baseline.output_bytes)
        enabled=replace(recipe,copy_policy=replace(recipe.copy_policy,enable_studio_native_metadata=True))
        copy=rebuild_native_trial_copy(enabled,cancelled=lambda:False)
        self.assertEqual(copy.output_bytes.count(STUDIO_NATIVE_METADATA_MARKER),1)
        span=copy.insertion_spans[0]
        self.assertEqual(copy.adapter_prefix,STUDIO_NATIVE_METADATA_MARKER+b'\n')
        self.assertTrue(copy.output_bytes.startswith(copy.adapter_prefix))
        self.assertEqual(copy.output_bytes[len(copy.adapter_prefix):span.output_start]+copy.output_bytes[span.output_end:],recipe.source_bytes)
        self.assertNotIn(b'generated by BambuStudio',copy.output_bytes)
        self.assertNotEqual(copy.emission_policy_identity,baseline.emission_policy_identity)
        # Only the declared comment differs; native motion and restored tags agree.
        self.assertEqual(copy.output_bytes.replace(STUDIO_NATIVE_METADATA_MARKER+b'\n',b''),baseline.output_bytes)

    def test_requires_real_orca_provenance_and_frozen_annotations(self):
        old=recipe_fixture(annotations=True)
        with self.assertRaisesRegex(ValueError,'provenance'):
            rebuild_native_trial_copy(replace(old,copy_policy=replace(old.copy_policy,enable_studio_native_metadata=True)),cancelled=lambda:False)
        recipe=orca_recipe()
        with self.assertRaisesRegex(ValueError,'annotations'):
            rebuild_native_trial_copy(replace(recipe,annotation_policy=None,copy_policy=replace(recipe.copy_policy,enable_studio_native_metadata=True)),cancelled=lambda:False)

    def test_pinned_consumer_contract_unknown_ignores_forced_height(self):
        # Studio v02.08.02.61 process_file enables producers, recognizes its
        # product substring, and gates native forced dimensions to that mode.
        source=b'; generated by OrcaSlicer 2.5.0-dev\n'
        def inferred_original_height(content):
            forced=0.2 if b'BambuStudio' in content else 0
            last_supplement_z=2.189
            return forced or 2.2-last_supplement_z
        self.assertAlmostEqual(inferred_original_height(source),.011)
        self.assertEqual(inferred_original_height(source+STUDIO_NATIVE_METADATA_MARKER),.2)

    def test_marker_satisfies_both_distinct_consumer_parser_gates(self):
        # GCodeProcessor substring detection and Config.cpp strict line prefix
        # are separate official v02.08.02.61 contracts.
        previous=b'; Smoothificator adapter: BambuStudio preview metadata dialect; original producer OrcaSlicer'
        detected=lambda line:b'BambuStudio' in line
        config_header=lambda line:line.startswith(b'; BambuStudio')
        self.assertTrue(detected(previous))
        self.assertFalse(config_header(previous))
        self.assertTrue(detected(STUDIO_NATIVE_METADATA_MARKER))
        self.assertTrue(config_header(STUDIO_NATIVE_METADATA_MARKER))
        self.assertIn(b'original producer OrcaSlicer',STUDIO_NATIVE_METADATA_MARKER)
        self.assertNotIn(b'generated by',STUDIO_NATIVE_METADATA_MARKER)
        config=b'; CONFIG_BLOCK_START\n; layer_height = 0.2\n; CONFIG_BLOCK_END\n'
        def forward_config_exists(content):
            lines=content.splitlines();header=next((i for i,line in enumerate(lines) if config_header(line)),None)
            return header is not None and any(line==b'; CONFIG_BLOCK_START' for line in lines[header+1:])
        self.assertFalse(forward_config_exists(config+STUDIO_NATIVE_METADATA_MARKER+b'\n'))
        self.assertTrue(forward_config_exists(STUDIO_NATIVE_METADATA_MARKER+b'\n'+config))
